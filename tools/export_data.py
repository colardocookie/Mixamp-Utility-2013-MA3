"""Export parameters and local test fixtures for the MixAmp web utility. OFFLINE ONLY.

Writes:
  webapp/factory-params.js       shipped: where the factory tables live in the MixAmp's program memory,
                                 their SHA-256 fingerprints, and derived numbers (fitted band parameters,
                                 starting curves). It contains no firmware bytes.
  webapp/test/fixtures/*.json    local only (gitignored): the raw factory tables and golden slot images
                                 built by ma3_preset_slot.py, used by the byte-for-byte parity tests.

The web app reads the factory tables from the user's own MixAmp when it connects.

Usage (from the project root): .venv/Scripts/python.exe webapp/tools/export_data.py
"""
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
import ma3_preset_slot as slots  # noqa: E402

EXAMPLE_GAINS = [2.8, -0.3, -0.6, -1.2, -3.0, -2.1, -0.6, 0.2, 1.7, 1.7, -3.0, 3.9, 0.1, -3.4]
# Factory curves A and B re-expressed on preset C's band grid (exact RBJ fits, rounded to 0.1 dB).
CURVE_A = [0.0, 0.5, 0.8, 1.6, 0.1, -0.5, -0.7, 0.0, 1.0, 1.9, 3.0, 4.2, 5.2, 6.9]
CURVE_B = [2.0, 3.5, 4.8, 5.6, 3.1, 0.5, -0.7, 1.0, 3.0, 1.9, 3.0, 4.2, 5.2, 5.9]
CODEC_TABLE = (0x1a654, 368)     # two 46-pair codec arrays, back to back: 0x1a654, 0x1a70c
AKM_TABLE = (0x1ae94, 729)       # three 243-byte DSP arrays, back to back: 0x1ae94, 0x1af87, 0x1b07a


def main():
    slots.firmware()  # SHA-256 check of the firmware baseline
    codec_raw = {va: slots.rom(va, 46 * 4) for va in (0x1a654, 0x1a70c)}
    akm_raw = {va: slots.factory_akm_bytes(va) for va in (0x1ae94, 0x1af87, 0x1b07a)}
    assert slots.rom(*CODEC_TABLE) == b''.join(codec_raw.values())
    assert slots.rom(*AKM_TABLE) == b''.join(akm_raw.values())

    params = dict(
        firmware=dict(version=3374, model=0x1005),
        tables=dict(codec=dict(address=CODEC_TABLE[0], length=CODEC_TABLE[1], arrays=[hex(v) for v in codec_raw], pairs=46),
                    akm=dict(address=AKM_TABLE[0], length=AKM_TABLE[1], arrays=[hex(v) for v in akm_raw], bytes=243)),
        tableSha256={hex(va): hashlib.sha256(b).hexdigest() for va, b in {**codec_raw, **akm_raw}.items()},
        descriptors={str(k): [hex(c), hex(a)] for k, (c, a) in slots.FACTORY_DESCRIPTORS.items()},
        factoryCBands=slots.FACTORY_C_BANDS,
        factoryCPregainDb=slots.FACTORY_C_PREGAIN_DB,
        maxNetGainDb=slots.MAX_NET_GAIN_DB,
        startingCurves=dict(curveA=CURVE_A, curveB=CURVE_B,
                            curveC=[round(b[1], 1) for b in slots.FACTORY_C_BANDS[:14]], flat=[0.0] * 14),
    )
    out = ROOT / 'webapp' / 'factory-params.js'
    out.write_text('// Generated by webapp/tools/export_data.py. Addresses, fingerprints and derived numbers only;\n'
                   '// the factory tables themselves are read from the connected MixAmp. Do not edit.\n'
                   'export const FACTORY_PARAMS = ' + json.dumps(params, indent=1) + ';\n', encoding='utf-8')

    fixtures = ROOT / 'webapp' / 'test' / 'fixtures'
    fixtures.mkdir(parents=True, exist_ok=True)
    (fixtures / 'factory-tables.json').write_text(json.dumps(dict(
        codec=slots.rom(*CODEC_TABLE).hex(), akm=slots.rom(*AKM_TABLE).hex())), encoding='utf-8')

    cases = []
    for slot, gains, pregain, codec in [
        (3, EXAMPLE_GAINS, -9.32, 'off'),
        (3, params['startingCurves']['curveC'], None, 'factory'),
        (0, CURVE_A, -12.0, 'factory'),
        (4, [0.0] * 14, -9.81, 'off'),
        (2, [10.0] * 14, None, 'factory'),     # forces the loudness cap
        (1, [-12.0, 12.0] * 7, -20.0, 'off'),
    ]:
        image = slots.custom_image(slot, gains, pregain, codec)
        cases.append(dict(kind='custom', slot=slot, gains=gains, pregain=pregain, codecEq=codec,
                          imageHex=image.hex(), sha256=hashlib.sha256(image).hexdigest(),
                          problems=slots.check_slot_image(slot, image, slots.FACTORY_DESCRIPTORS[slot][0])))
    for slot in range(5):
        image = slots.gate_off_clone(slot)
        cases.append(dict(kind='factoryClone', slot=slot, imageHex=image.hex(),
                          sha256=hashlib.sha256(image).hexdigest()))
    vectors = dict(
        cases=cases,
        adler=[dict(hex=h, value=slots.adler32_firmware(bytes.fromhex(h))) for h in ('', '616263', 'ff' * 980)],
        backupReads=[p['reports'][0].hex() for p in slots.backup_read_plan()[:2]],
        writeFirstReport=slots.slot_write_plan(3, slots.gate_off_clone(3), 33)['reports'][0].hex(),
    )
    (fixtures / 'golden.json').write_text(json.dumps(vectors, indent=1), encoding='utf-8')
    print(f'wrote {out} and {fixtures} ({len(cases)} image cases)')


if __name__ == '__main__':
    main()
